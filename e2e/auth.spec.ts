import { randomUUID } from 'node:crypto'
import { expect, test } from './fixtures'

test.use({ initialOwner: false, viewport: { width: 320, height: 740 } })

test('sets up the Owner in the browser, signs in automatically and later requires both credentials', async ({ page, backend }) => {
  const password = randomUUID()
  await expect(page.getByRole('heading', { name: 'Set up Lexyn' })).toBeVisible()
  await expect(page.getByLabel('Setup token')).toBeFocused()
  await page.getByLabel('Setup token').fill(backend.setupToken!)
  await page.getByLabel('Username', { exact: true }).fill('Lexyn.Admin')
  await page.getByLabel('Owner password').fill(password)
  await page.getByLabel('Confirm password').fill('different-password')
  await page.getByRole('button', { name: 'Create Owner' }).click()
  await expect(page.getByRole('alert')).toHaveText('The passwords do not match.')
  await page.getByLabel('Confirm password').fill(password)
  await page.getByRole('button', { name: 'Create Owner' }).click()
  await expect(page.getByRole('heading', { name: 'Your library is empty' })).toBeVisible()

  await page.getByRole('link', { name: 'Settings' }).click()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('heading', { name: 'Sign in to Lexyn' })).toBeVisible()
  await expect(page.getByLabel('Setup token')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  await page.getByLabel('Username', { exact: true }).fill('another-user')
  await page.getByLabel('Owner password').fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Invalid username or password.')
  await page.getByLabel('Username', { exact: true }).fill('lexyn.admin')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
})

test('requires a chosen username for the old default account and keeps its library', async ({ page, backend }) => {
  const { createAuth, initializeOwner } = await import('../server/auth/owner')
  const { migrate } = await import('../server/db/migrations/index')
  const password = randomUUID()
  await initializeOwner(backend.db, 'owner', password)
  const auth = createAuth(backend.db)
  const previous = await auth.login('owner', password)
  if (previous.status !== 'ok') throw new Error('Could not prepare previous session.')
  const deck = { id: randomUUID(), name: 'Existing vocabulary', createdAt: Date.now(), updatedAt: Date.now(), revision: 1 }
  backend.db.prepare('INSERT INTO decks (id, body, revision) VALUES (?, ?, 1)').run(deck.id, JSON.stringify(deck))
  backend.db.exec(`DROP TABLE vocabulary_jobs; DROP TABLE speech_credentials;
    DROP TABLE speech_settings; DROP TABLE speech_assets; PRAGMA user_version = 4;`)
  migrate(backend.db)
  expect(auth.session(previous.token)).toBeUndefined()
  expect((await auth.login('owner', password)).status).toBe('denied')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Choose your username' })).toBeVisible()
  await expect(page.getByLabel('Username', { exact: true })).toHaveValue('')
  await page.getByLabel('Setup token').fill(backend.setupToken!)
  await page.getByLabel('Username', { exact: true }).fill('My.Lexyn')
  await page.getByLabel('Current Owner password').fill('not-the-original-password')
  await page.getByRole('button', { name: 'Save username' }).click()
  await expect(page.getByRole('alert')).toHaveText('The current Owner password is incorrect.')
  await page.getByLabel('Current Owner password').fill(password)
  await page.getByRole('button', { name: 'Save username' }).click()
  await expect(page.getByRole('link', { name: 'Existing vocabulary' })).toBeVisible()
  expect(await auth.login('my.lexyn', password)).toMatchObject({ status: 'ok', ownerId: previous.ownerId })
})
