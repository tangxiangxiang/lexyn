import { randomUUID } from 'node:crypto'
import { expect, test } from './fixtures'

test.use({ initialOwner: false, englishUI: false, locale: 'en-US', viewport: { width: 320, height: 740 } })

test('defaults to Simplified Chinese, switches without reload and remembers the choice', async ({ page, backend }) => {
  const password = randomUUID()
  await expect(page.getByRole('heading', { name: '设置 Lexyn' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN')
  await expect(page.getByRole('radio', { name: '简体中文' })).toBeChecked()
  await page.getByLabel('设置令牌').fill(backend.setupToken!)
  await page.getByLabel('用户名', { exact: true }).fill('locale-admin')
  await page.getByLabel('管理员密码', { exact: true }).fill(password)
  await page.getByLabel('确认密码').fill('does-not-match')
  await page.getByRole('button', { name: '创建管理员' }).click()
  await expect(page.getByRole('alert')).toHaveText('两次输入的密码不一致。')
  await page.getByLabel('确认密码').fill(password)
  await page.getByRole('button', { name: '创建管理员' }).click()
  await expect(page.getByRole('heading', { name: '词库为空' })).toBeVisible()
  await page.getByRole('link', { name: '设置', exact: true }).click()
  await page.getByText('English', { exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page).toHaveTitle('Settings · Lexyn')
  await page.reload()
  await expect(page.getByRole('radio', { name: 'English' })).toBeChecked()
  await page.getByRole('link', { name: 'Progress', exact: true }).click()
  await expect(page.getByText('Learned for the first time today')).toBeVisible()
  await page.getByRole('link', { name: 'Settings', exact: true }).click()
  await page.getByText('简体中文', { exact: true }).click()
  await page.getByRole('link', { name: '复习', exact: true }).click()
  await expect(page.getByText('待首次回忆')).toBeVisible()
  await expect(page).toHaveTitle('复习 · Lexyn')
})
